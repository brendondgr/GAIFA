"""Generate the README banner from GAIFA's logo (plan 50.4).

Reads web/favicon.svg (the mark the UI shows) and writes docs/assets/header.svg with the logo, the
name, the tagline and two chip rows. GitHub won't render one SVG referenced from inside another, so
the banner embeds the logo's paths; generating it keeps that copy in step with the one original.

The tagline repeats the README's opening sentence. Change one, change both, then re-run this.

    python3 docs/assets/make_header.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOGO = ROOT / "web/favicon.svg"
LOGO_BOX = 32
OUT = ROOT / "docs/assets/header.svg"

TITLE = "GAIFA"
TAGLINE = (
    "Build your own AI apps as mods, and use them all",
    "through one agent that learns how you work.",
)
MEANING = ("Great, Another Interface For Agents", "say “guy-fuh”")  # under the tagline; the initials in the accent
# Dot colours are GitHub's own, from github/linguist languages.yml, so the row reads as familiar.
LANGUAGES = [
    ("Python", "#3572a5"),
    ("JavaScript", "#f1e05a"),
    ("HTML", "#e34c26"),
    ("TypeScript", "#3178c6"),
    ("Shell", "#89e051"),
]
STACK = [(n, None) for n in ("FastAPI", "OpenAPI", "MCP", "SQLite", "uv", "React")]

# The UI's own dark theme (web/Hub.dc.html): --bg, --bd, --card, --tx, --mut and the amber accent.
PANEL_BG, PANEL_EDGE = "#0B0E14", "#1D2430"
CHIP_BG, CHIP_EDGE = "#11151D", "#2A3547"
TEXT, CHIP_TEXT, MUTED, ACCENT = "#E6EAF2", "#C3CAD8", "#8A94A6", "#FFB224"

SANS = "ui-sans-serif,-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif"
MONO = "ui-monospace,SFMono-Regular,Menlo,Consolas,'DejaVu Sans Mono',monospace"

W = 1000
MARK, MARK_CY = 120.0, 106.0                    # logo size, and its centre from the top
TITLE_Y, TITLE_SIZE = 240, 68
TAGLINE_Y, TAGLINE_SIZE, LINE_H = 280, 19, 28
MEANING_Y, MEANING_SIZE = 350, 15
ROWS_Y, ROW_H = 382, 46                         # first chip row, and the gap to the next
CHIP_H, CHIP_FS, CHIP_GAP, CHIP_PAD = 32, 14.0, 10.0, 15.0
DOT_R, DOT_GUTTER, ADVANCE = 4.0, 13.0, 0.6

rows = [r for r in (LANGUAGES, STACK) if r]
H = int(ROWS_Y + ROW_H * (len(rows) - 1) + CHIP_H + 28)


def logo_paths():
    raw = re.sub(r"<metadata>.*?</metadata>", "", LOGO.read_text(), flags=re.S)
    return raw[raw.index(">", raw.index("<svg")) + 1 : raw.rindex("</svg>")].strip()


def chip_row(items, y):
    widths = [
        CHIP_PAD * 2 + len(label) * CHIP_FS * ADVANCE + (DOT_GUTTER if dot else 0.0)
        for label, dot in items
    ]
    x = (W - (sum(widths) + CHIP_GAP * (len(items) - 1))) / 2
    parts = []
    for (label, dot), width in zip(items, widths):
        text_x = x + CHIP_PAD
        parts.append(
            f'<rect x="{x:.1f}" y="{y:g}" width="{width:.1f}" height="{CHIP_H}" '
            f'rx="{CHIP_H / 2:g}" fill="{CHIP_BG}" stroke="{CHIP_EDGE}" />'
        )
        if dot:
            parts.append(
                f'<circle cx="{text_x + DOT_R:.1f}" cy="{y + CHIP_H / 2:.1f}" '
                f'r="{DOT_R:g}" fill="{dot}" />'
            )
            text_x += DOT_GUTTER
        parts.append(
            f'<text x="{text_x:.1f}" y="{y + CHIP_H / 2 + 5:.1f}" font-family="{MONO}" '
            f'font-size="{CHIP_FS:g}" fill="{CHIP_TEXT}">{label}</text>'
        )
        x += width + CHIP_GAP
    return "\n  ".join(parts)


cx = W / 2
taglines = "\n  ".join(
    f'<text x="{cx:g}" y="{TAGLINE_Y + i * LINE_H:g}" text-anchor="middle" '
    f'font-family="{SANS}" font-size="{TAGLINE_SIZE}" fill="{MUTED}">{line}</text>'
    for i, line in enumerate(TAGLINE)
)
initials = "\u00a0".join(  # no-break spaces: a renderer may drop plain ones next to a tspan
    f'<tspan fill="{ACCENT}" font-weight="700">{w[0]}</tspan>{w[1:]}' for w in MEANING[0].split(" ")
)
meaning = (
    f'<text x="{cx:g}" y="{MEANING_Y}" text-anchor="middle" font-family="{MONO}" '
    f'font-size="{MEANING_SIZE}" fill="{CHIP_TEXT}">{initials}'
    f'\u00a0\u00a0\u00b7\u00a0\u00a0<tspan fill="{MUTED}">{MEANING[1]}</tspan></text>'
)
chips = "\n  ".join(chip_row(row, ROWS_Y + i * ROW_H) for i, row in enumerate(rows))

OUT.write_text(f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" \
width="{W}" height="{H}" role="img" aria-label="{TITLE}">
  <!-- Generated by docs/assets/make_header.py - edit that, not this. -->
  <rect x="0.5" y="0.5" width="{W - 1}" height="{H - 1}" rx="24" fill="{PANEL_BG}" \
stroke="{PANEL_EDGE}" />
  <g transform="translate({cx - MARK / 2:.1f},{MARK_CY - MARK / 2:.1f}) \
scale({MARK / LOGO_BOX:.6f})">
    {logo_paths()}
  </g>
  <text x="{cx:g}" y="{TITLE_Y}" text-anchor="middle" font-family="{SANS}" \
font-size="{TITLE_SIZE}" font-weight="700" letter-spacing="2" fill="{TEXT}">{TITLE}</text>
  {taglines}
  {meaning}
  {chips}
</svg>
""")
print(f"wrote {OUT.relative_to(ROOT)}")
