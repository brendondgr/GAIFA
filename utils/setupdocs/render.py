"""The generated parts: a model doc's block, the index in docs/setup/README.md, the support matrix in docs/platforms.md
and the table in docs/turning-things-on.md (capability-enablement 8.3)."""

from __future__ import annotations

import os
import posixpath
from pathlib import Path
from typing import Any

from .block import ACCELS, OSES
from .envs import Env

SYSTEMS = {"linux": "Linux", "wsl": "Windows (WSL2)", "darwin": "macOS"}
RUNS_ON = {"rocm": "ROCm", "cuda": "CUDA", "xpu": "Intel XPU", "mps": "Apple MPS", "vulkan": "Vulkan", "cpu": "CPU"}

START = "<!-- generated by gaifa docs: do not edit between these markers -->"
END = "<!-- end generated -->"
HAND_WITH_SOURCE = "## What to look for\n\n## Notes\n"
HAND_NO_SOURCE = "## Where to get it\n\n" + HAND_WITH_SOURCE


def gb(n: float) -> str:
    if not n:
        return "—"
    if n >= 1e9:
        return f"{n / 1e9:.1f} GB"
    if n >= 1e6:
        return f"{n / 1e6:.0f} MB"
    return f"{n / 1e3:.0f} kB" if n >= 1e3 else f"{n} B"


def size(e: dict[str, Any]) -> int:
    return sum(int(f.get("size_bytes") or 0) for f in e.get("files", []))


def link(frm: Path, to: Path) -> str:
    return os.path.relpath(to, frm.parent).replace(os.sep, "/")


def source_line(e: dict[str, Any]) -> str:
    s = e.get("source") or {}
    t = s.get("type")
    if t == "huggingface" and s.get("repo"):
        rev = s.get("revision")
        at = f" at `{rev[:12]}`" if rev and rev != "main" else ""
        return f"Hugging Face [{s['repo']}](https://huggingface.co/{s['repo']}){at}"
    if t == "url" and s.get("url"):
        return f"<{s['url']}>"
    if t == "created":
        return "made on this machine" + (f" ({s['note']})" if s.get("note") else "")
    if t == "local":
        return "not recorded" + (f": {s['note']}" if s.get("note") else "")
    return "not recorded"


def has_source(e: dict[str, Any]) -> bool:
    s = e.get("source") or {}
    return (s.get("type") == "huggingface" and bool(s.get("repo"))) or (s.get("type") == "url" and bool(s.get("url"))) or s.get("type") == "created"


def _inner(e: dict[str, Any]) -> list[str]:
    """The recorded files, relative to the model's own folder (or its snapshot, for the HF cache)."""
    base = e["path"]
    out = []
    for f in e.get("files", []):
        p = f["path"]
        rel = p[len(base) + 1:] if p.startswith(base + "/") else posixpath.basename(p)
        if base.startswith("hf-cache/"):
            if not rel.startswith("snapshots/") or rel.count("/") < 2:
                continue                         # refs/main, blobs: the cache's own bookkeeping, not repo files
            rel = rel.split("/", 2)[2]
        out.append(rel)
    return out


def fetch(e: dict[str, Any], mid: str) -> list[str]:
    """Shell commands that put the model where the registry expects it, run from the project folder."""
    s = e.get("source") or {}
    path = e["path"]
    if s.get("type") == "url" and s.get("url"):
        return [f'curl -L --fail -o "data/models/{path}.part" "{s["url"]}" && mv "data/models/{path}.part" "data/models/{path}"']
    if s.get("type") != "huggingface" or not s.get("repo"):
        return []
    rev = f" --revision {s['revision']}" if s.get("revision") and s["revision"] != "main" else ""
    hf = "uvx --from huggingface_hub hf download"
    files = " ".join(_inner(e))
    if path.startswith("hf-cache/"):
        return [f"HF_HOME=data/models/hf-cache {hf} {s['repo']} {files}{rev}".replace("  ", " ")]
    if len(e.get("files", [])) == 1 and e["files"][0]["path"] == path:
        name = posixpath.basename(path)
        tmp = f"data/state/downloads/{mid}"
        return [f'{hf} {s["repo"]} --include "*{name}"{rev} --local-dir {tmp}',
                f'mkdir -p "data/models/{posixpath.dirname(path)}" && find {tmp} -name "{name}" -exec mv {{}} "data/models/{path}" \\; && rm -r {tmp}']
    return [f"{hf} {s['repo']} {files}{rev} --local-dir data/models/{path}"]


def model_block(mid: str, e: dict[str, Any], used_by: list[str], envs: list[Env], refs: list[str], doc: Path, root: Path) -> str:
    files = e.get("files", [])
    rows = [
        ("Id", f"`{mid}`"),
        ("Kind", e.get("kind") or "—"),
        ("Format", e.get("format") or "—"),
        ("Size", f"{gb(size(e))} in {len(files)} file{'s' if len(files) != 1 else ''}"),
        ("Where it goes", f"`data/models/{e['path']}`"),
        ("Source", source_line(e)),
        ("Used by", ", ".join(f"`{u}`" for u in used_by) or "no mod"),
        ("Environment", ", ".join(f"[{v.title}]({link(doc, v.path)})" for v in envs) or "none yet"),
    ]
    if refs:
        rows.append(("Referenced by", ", ".join(f"[`{r.split('/', 2)[2] if r.count('/') >= 2 else r}`]({link(doc, root / r)})" for r in refs)))
    if e.get("notes"):
        rows.append(("Registry notes", str(e["notes"]).replace("\n", " ").replace("|", "\\|")))
    out = [START, f"# {e.get('name') or mid}", "", "| | |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in rows]
    out += ["", "### Files", "", "| File | Role | Size | SHA-256 |", "|---|---|---|---|"]
    for f in files:
        sha = f.get("sha256")
        out.append(f"| `{f['path']}` | {f.get('role') or '—'} | {gb(int(f.get('size_bytes') or 0))} | {f'`{sha}`' if sha else 'not recorded'} |")
    cmds = fetch(e, mid)
    if cmds:
        out += ["", "### Get it", "", f"From the project folder (`uvx` runs Hugging Face's CLI without installing it; gated repos need `hf auth login` first, see [host.md]({link(doc, root / 'docs/setup/host.md')}#6-accounts-and-licences)):", ""]
        for c in cmds:
            out += ["```bash", c, "```", ""]
        out.pop()
    out += [END]
    return "\n".join(out)


def orphan_block(mid: str) -> str:
    return "\n".join([START, f"# {mid}", "", f"**Not in the registry.** `{mid}` was removed from `data/models/registry.json`; this doc is kept because it has hand-written notes. Delete it when they're no longer useful.", END])


def mods_index(envs: list[Env], readme: Path) -> str:
    """The block in docs/setup/README.md: every mod and its setup docs. Tracked files only, no models."""
    out = [START]
    if not envs:
        out.append("*No setup docs yet: they go in `services/<id>/setup/` (mods.md §9).*")
    else:
        out += ["| Mod | What it gives you | GPU | Runs on | Disk | Setup docs |", "|---|---|---|---|---|---|"]
        by_mod: dict[str, list[Env]] = {}
        for v in envs:
            by_mod.setdefault(v.mod, []).append(v)
        for mod in sorted(by_mod):
            vs = sorted(by_mod[mod], key=lambda v: v.id)
            summary = " · ".join(v.setup.summary for v in vs if v.setup.summary) or "—"
            gpus = [v.setup.gpu for v in vs if v.setup.gpu is not None]
            gpu = "—" if not gpus else "yes" if any(gpus) else "no"
            accels = {a for v in vs if v.setup.summary for a in v.setup.runs_on()}
            runs = " · ".join(RUNS_ON[a] for a in ACCELS if a in accels) or "—"
            disks = [v.setup.disk_gb for v in vs if v.setup.disk_gb is not None]
            disk = gb(sum(disks) * 1e9) if disks else "—"
            docs = ", ".join(f"[{v.title}]({link(readme, v.path)})" for v in vs)
            finds = [f for v in vs for f in v.setup.find]          # capability-enablement 7.1: where its models are compared
            if finds:
                docs += " · models compared: " + ", ".join(f"[{f.label}]({f.url})" for f in finds)
            out.append(f"| `{mod}` | {summary} | {gpu} | {runs} | {disk} | {docs} |")
    out.append(END)
    return "\n".join(out)


def inventory_index(models: list[tuple[str, dict[str, Any], list[Env]]], index: Path) -> str:
    """data/state/setup/models/README.md: this machine's models (local, gitignored)."""
    out = ["# This machine's models", "",
           "Written by `gaifa docs` from `data/models/registry.json`. It lists the models on this machine, not what GAIFA needs: "
           "which models to set up is your choice, per mod (`gaifa setup`, `docs/setup/`).", "",
           f"{len(models)} models, {gb(sum(size(e) for _, e, _ in models))} in all.", "",
           "| Model | Kind | Size | Environment | Source |", "|---|---|---|---|---|"]
    for mid, e, vs in sorted(models, key=lambda t: (t[1].get("kind") or "", t[0])):
        envs = ", ".join(f"[{v.title}]({link(index, v.path)})" for v in vs) or "none"
        out.append(f"| [{e.get('name') or mid}]({mid}.md) | {e.get('kind') or '—'} | {gb(size(e))} | {envs} | {'recorded' if has_source(e) else 'not recorded'} |")
    return "\n".join(out) + "\n"


def platforms_matrix(envs: list[Env], page: Path) -> str:
    """The block in docs/platforms.md (plan 40.4): each setup, and on each system the accels its variants
    declare, tested or not, from their `tested` flags."""
    out = [START, "",
           "✓ tested: the variant has run for real on that system (where and when: its setup doc's *Tested with*). "
           "○ untested: declared, not run there yet; the field test (plan 40.5, 40.6) checks it. "
           "—: not available there. Nothing has run on a Mac (CI, which ran the hub's tests there, was turned off on 2026-10-22). "
           "`gaifa hardware` shows a machine's accels; `gaifa setup --plan` names the variant it picks.", ""]
    if not envs:
        out += ["*No setup docs yet.*", END]
        return "\n".join(out)
    out += ["| Mod | Setup | " + " | ".join(SYSTEMS[o] for o in OSES) + " |", "|---|---|" + "---|" * len(OSES)]
    for v in sorted(envs, key=lambda v: (v.mod, v.id)):
        cells = []
        for o in OSES:
            marks = {a: ("✓" if o in var.tested else "○") for var in v.setup.effective_variants() if o in var.os for a in [var.accel]}
            cells.append(" · ".join(f"{RUNS_ON[a]} {marks[a]}" for a in ACCELS if a in marks) or "—")
        out.append(f"| `{v.mod}` | [{v.title}]({link(page, v.path)}) | " + " | ".join(cells) + " |")
    out.append(END)
    return "\n".join(out)


def turning_on(envs: list[Env], page: Path, root: Path) -> str:
    """The table in docs/turning-things-on.md (capability-enablement 8.3): each mod, what it gives, recommended, its size
    (environments and default models), what a chat can't do without it (its manifest's `[agent] provides`), the command
    and where its models are compared."""
    import tomllib
    out = [START]
    by_mod: dict[str, list[Env]] = {}
    for v in envs:
        by_mod.setdefault(v.mod, []).append(v)
    if not by_mod:
        out += ["*No setup docs yet.*", END]
        return "\n".join(out)
    out += ["| Mod | What it gives you | Recommended | Size | Without it, a chat can't… | Turn it on | Models compared |",
            "|---|---|---|---|---|---|---|"]
    for mod in sorted(by_mod, key=lambda m: (not any(v.setup.recommended for v in by_mod[m] if v.id == m), m)):
        vs = sorted(by_mod[mod], key=lambda v: v.id)
        own = next((v for v in vs if v.id == mod), None)
        gives = (own.setup.summary or own.title) if own else " · ".join(v.setup.summary for v in vs if v.setup.summary) or vs[0].title
        own = own or vs[0]
        try:
            provides = str((tomllib.loads((root / "services" / mod / "service.toml").read_text()).get("agent") or {}).get("provides") or "")
        except (OSError, tomllib.TOMLDecodeError):
            provides = ""
        disk = sum(v.setup.disk_gb or 0 for v in vs) + sum(s.size_gb for v in vs for s in v.setup.suggest if s.required or s.default)
        finds = ", ".join(f"[{f.label}]({f.url})" for v in vs for f in v.setup.find) or "—"
        rec = "yes" if any(v.setup.recommended for v in vs if v.id == mod) else "—"
        out.append(f"| [`{mod}`]({link(page, own.path)}) | {gives} | {rec} | {gb(disk * 1e9) if disk else '—'} | "
                   f"{provides or '—'} | `gaifa setup {mod}` | {finds} |")
    out.append(END)
    return "\n".join(out)
