"""The generated parts: a model doc's block and the index in docs/setup/README.md."""

from __future__ import annotations

import os
import posixpath
from pathlib import Path
from typing import Any

from .envs import Env

START = "<!-- generated by aihub docs: do not edit between these markers -->"
END = "<!-- end generated -->"
HAND_WITH_SOURCE = "## What to look for\n\n## Notes\n"
HAND_NO_SOURCE = "## Where to get it\n\n" + HAND_WITH_SOURCE


def gb(n: float) -> str:
    if not n:
        return "—"
    if n >= 1e9:
        return f"{n / 1e9:.1f} GB"
    if n >= 1e6:
        return f"{n / 1e6:.0f} MB"
    return f"{n / 1e3:.0f} kB" if n >= 1e3 else f"{n} B"


def size(e: dict[str, Any]) -> int:
    return sum(int(f.get("size_bytes") or 0) for f in e.get("files", []))


def link(frm: Path, to: Path) -> str:
    return os.path.relpath(to, frm.parent).replace(os.sep, "/")


def source_line(e: dict[str, Any]) -> str:
    s = e.get("source") or {}
    t = s.get("type")
    if t == "huggingface" and s.get("repo"):
        rev = s.get("revision")
        at = f" at `{rev[:12]}`" if rev and rev != "main" else ""
        return f"Hugging Face [{s['repo']}](https://huggingface.co/{s['repo']}){at}"
    if t == "url" and s.get("url"):
        return f"<{s['url']}>"
    if t == "created":
        return "made on this machine" + (f" ({s['note']})" if s.get("note") else "")
    if t == "local":
        return "not recorded" + (f": {s['note']}" if s.get("note") else "")
    return "not recorded"


def has_source(e: dict[str, Any]) -> bool:
    s = e.get("source") or {}
    return (s.get("type") == "huggingface" and bool(s.get("repo"))) or (s.get("type") == "url" and bool(s.get("url"))) or s.get("type") == "created"


def _inner(e: dict[str, Any]) -> list[str]:
    """The recorded files, relative to the model's own folder (or its snapshot, for the HF cache)."""
    base = e["path"]
    out = []
    for f in e.get("files", []):
        p = f["path"]
        rel = p[len(base) + 1:] if p.startswith(base + "/") else posixpath.basename(p)
        if base.startswith("hf-cache/") and rel.startswith("snapshots/"):
            rel = rel.split("/", 2)[2] if rel.count("/") >= 2 else rel
        out.append(rel)
    return out


def fetch(e: dict[str, Any], mid: str) -> list[str]:
    """Shell commands that put the model where the registry expects it, run from the project folder."""
    s = e.get("source") or {}
    path = e["path"]
    if s.get("type") == "url" and s.get("url"):
        return [f'curl -L --fail -o "data/models/{path}.part" "{s["url"]}" && mv "data/models/{path}.part" "data/models/{path}"']
    if s.get("type") != "huggingface" or not s.get("repo"):
        return []
    rev = f" --revision {s['revision']}" if s.get("revision") and s["revision"] != "main" else ""
    hf = "uvx --from huggingface_hub hf download"
    files = " ".join(_inner(e))
    if path.startswith("hf-cache/"):
        return [f"HF_HOME=data/models/hf-cache {hf} {s['repo']} {files}{rev}".replace("  ", " ")]
    if len(e.get("files", [])) == 1 and e["files"][0]["path"] == path:
        name = posixpath.basename(path)
        tmp = f"data/state/downloads/{mid}"
        return [f'{hf} {s["repo"]} --include "*{name}"{rev} --local-dir {tmp}',
                f'mkdir -p "data/models/{posixpath.dirname(path)}" && find {tmp} -name "{name}" -exec mv {{}} "data/models/{path}" \\; && rm -r {tmp}']
    return [f"{hf} {s['repo']} {files}{rev} --local-dir data/models/{path}"]


def model_block(mid: str, e: dict[str, Any], used_by: list[str], envs: list[Env], refs: list[str], doc: Path, root: Path) -> str:
    files = e.get("files", [])
    rows = [
        ("Id", f"`{mid}`"),
        ("Kind", e.get("kind") or "—"),
        ("Format", e.get("format") or "—"),
        ("Size", f"{gb(size(e))} in {len(files)} file{'s' if len(files) != 1 else ''}"),
        ("Where it goes", f"`data/models/{e['path']}`"),
        ("Source", source_line(e)),
        ("Used by", ", ".join(f"`{u}`" for u in used_by) or "no mod"),
        ("Environment", ", ".join(f"[{v.title}]({link(doc, v.path)})" for v in envs) or "none yet"),
    ]
    if refs:
        rows.append(("Referenced by", ", ".join(f"[`{r.split('/', 2)[2] if r.count('/') >= 2 else r}`]({link(doc, root / r)})" for r in refs)))
    if e.get("notes"):
        rows.append(("Registry notes", str(e["notes"]).replace("\n", " ").replace("|", "\\|")))
    out = [START, f"# {e.get('name') or mid}", "", "| | |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in rows]
    out += ["", "### Files", "", "| File | Role | Size | SHA-256 |", "|---|---|---|---|"]
    for f in files:
        sha = f.get("sha256")
        out.append(f"| `{f['path']}` | {f.get('role') or '—'} | {gb(int(f.get('size_bytes') or 0))} | {f'`{sha}`' if sha else 'not recorded'} |")
    cmds = fetch(e, mid)
    if cmds:
        out += ["", "### Get it", "", "From the project folder (`uvx` runs Hugging Face's CLI without installing it; gated repos need `hf auth login` first, see [host.md](../host.md#6-accounts-and-licences)):", ""]
        for c in cmds:
            out += ["```bash", c, "```", ""]
        out.pop()
    out += [END]
    return "\n".join(out)


def orphan_block(mid: str) -> str:
    return "\n".join([START, f"# {mid}", "", f"**Not in the registry.** `{mid}` was removed from `data/models/registry.json`; this doc is kept because it has hand-written notes. Delete it when they're no longer useful.", END])


def index_block(models: list[tuple[str, dict[str, Any], list[Env]]], envs: list[Env], readme: Path, models_dir: Path) -> str:
    out = [START]
    if envs:
        out += ["| Environment | Mod | Models | Size |", "|---|---|---|---|"]
        for v in sorted(envs, key=lambda v: (v.mod, v.id)):
            mine = [e for _, e, vs in models if v in vs]
            out.append(f"| [{v.title}]({link(readme, v.path)}) | `{v.mod}` | {len(mine)} | {gb(sum(size(e) for e in mine))} |")
    else:
        out.append("*No environment docs yet: they go in `services/<id>/setup/` (mods.md §9).*")
    out += ["", f"**Models** ({len(models)}, {gb(sum(size(e) for _, e, _ in models))} in all):", ""]
    out += ["| Model | Kind | Size | Environment | Source |", "|---|---|---|---|---|"]
    for mid, e, vs in sorted(models, key=lambda t: (t[1].get("kind") or "", t[0])):
        doc = link(readme, models_dir / f"{mid}.md")
        out.append(f"| [{e.get('name') or mid}]({doc}) | {e.get('kind') or '—'} | {gb(size(e))} | {', '.join(v.title for v in vs) or 'none yet'} | {'recorded' if has_source(e) else '**not recorded**'} |")
    out.append(END)
    return "\n".join(out)
